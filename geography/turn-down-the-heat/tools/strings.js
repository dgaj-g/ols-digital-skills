#!/usr/bin/env node
/* Writes tools/STRINGS.md from ../content.js — every word she reads, by part, with its key.
   content.js is the source; never edit STRINGS.md by hand. node strings.js */
const vm = require('vm'), fs = require('fs'), path = require('path');
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../content.js'), 'utf8'), ctx);
const C = ctx.window.TDTH;
const NOT_WORDS = /(^|\.)(id|img|zone|src|layout|type|kind|key|icon|color|colour|tone|url|file)$|\.accept\.\d+$/;
const lines = ['# STRINGS — Turn Down the Heat', '', 'Generated by `tools/strings.js` from `content.js` on ' + new Date().toISOString().slice(0, 10) + '. The build copies content.js; it never retypes these.', ''];
let n = 0;
function section(title, obj, base) {
  const rows = [];
  (function walk(o, p) {
    if (typeof o === 'string') { if (!NOT_WORDS.test(p) && /[A-Za-z]/.test(o)) rows.push('- `' + p + '` ' + o.replace(/\n/g, ' ')); return; }
    if (o && typeof o === 'object') Object.keys(o).forEach(k => walk(o[k], p + '.' + k));
  })(obj, base);
  if (!rows.length) return;
  lines.push('## ' + title, '', ...rows, '');
  n += rows.length;
}
Object.keys(C).forEach(k => {
  if (k === 'parts') C.parts.forEach((p, i) => section('Part ' + p.k + ': ' + p.name, p, 'parts.' + i));
  else section(k, C[k], k);
});
fs.writeFileSync(path.join(__dirname, 'STRINGS.md'), lines.join('\n'));
console.log('STRINGS.md: ' + n + ' strings');
