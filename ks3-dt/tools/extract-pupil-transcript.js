#!/usr/bin/env node
/* extract-pupil-transcript.js — EVERYTHING SHE SEES, IN HER ORDER, AND NOTHING ELSE.
   (L4_SIT_FIXES_SPEC Part E 7b; audit gap G0 — the root gap.)

   WHY THIS EXISTS, in Damien's words (DFM 193d): "throwing more rules is not
   enough… is there not a better approach?" It is the second half of his answer:
   clarity is produced at WRITING time and verified by a SEPARATED cold read. A
   cold read needs an artefact — the screens as the child meets them, with no
   design notes, no rule numbers, no author's intent attached — or the person
   judging is really judging what they meant to write.

   And DFM 194's finding underneath it: the judged pass had no separation and
   left NO EVIDENCE. So this prints the reader's own transcript, and the verdicts
   written against it are filed in COLD_READ_VERDICTS_L4_L5.md. Any sentence in
   the final transcript with no verdict row fails the round (rule: no unjudged
   surface).

   IT IS NOT A GATE. Nothing here passes or fails a build; it is the paper the
   judgement is made on. Wiring a pass/fail rule onto it would quietly turn the
   judged layer back into a mechanical one, which is the exact swap DFM 193d
   forbids.

   Film captions are placed AT THE CHUNK THAT HOSTS THE FILM, because that is
   where she meets them — and after the Lesson 5 split, a chunk can host only
   half a film, so each caption is printed under the chapter it belongs to.

   Usage:  node extract-pupil-transcript.js j1-04
           node extract-pupil-transcript.js j1-05 --out <path>
*/
const fs = require('fs');
const path = require('path');
const Q = require('./record-tutorial/qa-language.js');

const id = process.argv[2];
if (!id || /^--/.test(id)) {
  console.error('usage: node extract-pupil-transcript.js <lessonId>   e.g. j1-04');
  process.exit(2);
}
const outIdx = process.argv.indexOf('--out');
const OUT = outIdx > 0 ? process.argv[outIdx + 1]
  : path.join(__dirname, '../../qa-l2-l5-review/l4-sit-fixes/transcript-' + id + '.txt');

const lesson = Q.loadLessons().find(L => L.fileId === id);
if (!lesson) { console.error('no such lesson: ' + id); process.exit(1); }

/* the film that plays inside this lesson, caption by caption, in take order */
const film = Q.collectFilmStrings();
const mine = film.strings.filter(f => f.lesson === id);
const byChunk = {};
mine.forEach(f => {
  const set = Q.FILM_MAP[f.set] || {};
  const ch = set.chunkId || '(unplaced)';
  (byChunk[ch] = byChunk[ch] || []).push(f);
});

const L = lesson.json;
const lines = [];
const rule = (c) => c.repeat(78);

lines.push(rule('='));
lines.push('PUPIL TRANSCRIPT — ' + id + ' — ' + (L.title || ''));
lines.push('every string this lesson can put in front of a pupil, in the order she meets it');
lines.push('read as ' + ({ j1: 'an 11 or 12-year-old', j2: 'an 11 or 12-year-old', j3: 'an 11 or 12-year-old' }[lesson.year] || 'an 11 or 12-year-old'));
lines.push('generated by extract-pupil-transcript.js — a judging artefact, NOT a gate');
lines.push(rule('='));
lines.push('');

/* the collector's walk IS the authored order, and the authored order is the
   render order for every engine in this platform (each one reads its config top
   to bottom). Grouping by chunk is what makes it a screen-by-screen read. */
const strings = lesson.strings;
const chunkOf = (p) => {
  const m = String(p).match(/^j\d-[a-z0-9]+ › ([a-z0-9-]+)/i);
  return m ? m[1] : '(lesson)';
};
const order = [];
(L.chunks || []).forEach(c => order.push(c.id));

const seen = new Set();
const emit = (label, chunkId, mins, engine) => {
  lines.push('');
  lines.push(rule('-'));
  lines.push('SCREEN: ' + label + (mins ? '   [' + mins + ' min]' : '') + (engine ? '   (' + engine + ')' : ''));
  lines.push(rule('-'));
  strings.filter(s => chunkOf(s.path) === chunkId).forEach(s => {
    seen.add(s.path);
    lines.push('');
    lines.push('  · ' + s.path.replace(/^.*? › /, ''));
    String(s.text).split('\n').forEach(t => lines.push('      ' + t));
  });
  (byChunk[chunkId] || []).forEach((f, i) => {
    if (i === 0) {
      lines.push('');
      lines.push('  ---- THE FILM PLAYS HERE — every caption she reads on screen ----');
    }
    lines.push('      [' + f.set + ' ' + f.chapter + '] ' + Q.filmRendered(f.raw));
  });
};

(L.chunks || []).forEach(c => emit(c.title || c.id, c.id, c.minutes, c.engine));

/* anything the walk found that no chunk claimed (lesson title, keys.explain) */
const orphans = strings.filter(s => !seen.has(s.path));
if (orphans.length) {
  lines.push('');
  lines.push(rule('-'));
  lines.push('SHOWN OUTSIDE A CHUNK — the lesson tile, and the marking she reads after answering');
  lines.push(rule('-'));
  orphans.forEach(s => {
    lines.push('');
    lines.push('  · ' + s.path.replace(/^.*? › /, ''));
    String(s.text).split('\n').forEach(t => lines.push('      ' + t));
  });
}

const filmCount = mine.length;
lines.push('');
lines.push(rule('='));
lines.push('TOTAL: ' + strings.length + ' card/config sentences + ' + filmCount + ' film captions');
lines.push(rule('='));

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n') + '\n');
console.log('wrote ' + OUT);
console.log('  ' + strings.length + ' pupil strings across ' + (L.chunks || []).length +
  ' screens, plus ' + filmCount + ' film captions');
