#!/usr/bin/env node
/* qa-engine-debt.js — THE RENDERED HALF OF THE LEDGER RATCHET (S1).
 *
 * `engine-strings.js --check` ratchets the SOURCE: no round may add an engine
 * sentence. This ratchets what a pupil actually MEETS: no lesson may start
 * rendering a sentence the ledger still calls OUTSTANDING.
 *
 * The two are different questions and the second is the one that failed him.
 * "Exit check — part 2" added no debt on 27 August — the literal had been in
 * `engines.js` for weeks. What changed was that a NEW CARD mounted the engine
 * that says it, and the parked sentence walked onto a pupil's screen telling
 * her she was in an exit check while she was in a training build. A source
 * ratchet cannot see that. This can.
 *
 * WHERE THE NUMBERS COME FROM. The walkers already stand on every screen of
 * every lesson and already ask, on every state, whether the screen is rendering
 * an outstanding ledger row (lib/ledger.js). Each writes what it saw to
 * `out/rendered-debt/<lesson>.json`. This reads those sidecars: no second
 * browser, no second walk, no hand list (DFM 271).
 *
 *   node qa-engine-debt.js            rewrite ENGINE_STRINGS_RENDERED.md from
 *                                     the sidecars — the new ceiling
 *   node qa-engine-debt.js --check    FAIL if a lesson renders a row that is
 *                                     not in the committed ceiling
 *
 * WHY A CEILING AND NOT A BAN. Six lessons are signed off and locked, and they
 * render old debt today. Failing them would re-open approvals he has given —
 * "leave things the way they are" (DFM 273a), and DFM 221's report-never-fix.
 * So what the shipped build already showed is printed on every single run, in
 * full, and never quietly carried; anything NEW is a failure.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const RD = require('./lib/rendered-debt.js');
const LD = require('./lib/ledger.js');

const CHECK = process.argv.includes('--check');
const sidecars = fs.existsSync(RD.SIDE)
  ? fs.readdirSync(RD.SIDE).filter(f => f.endsWith('.json'))
  : [];

if (!sidecars.length) {
  console.log((CHECK ? 'FAIL  ' : '') +
    'no walker has written a rendered-debt sidecar yet (' + RD.SIDE + ').');
  console.log('      Run the walkers first — this file reports what THEY stood on, and a gate');
  console.log('      that passes with no evidence is the thing it exists to stop (DFM 204).');
  process.exit(CHECK ? 1 : 0);
}

const seen = {};
sidecars.forEach(f => {
  try {
    const j = JSON.parse(fs.readFileSync(path.join(RD.SIDE, f), 'utf8'));
    seen[String(j.lesson)] = (j.seen || []).map(String);
  } catch (e) { console.log('  ! unreadable sidecar ' + f + ': ' + e.message); }
});

if (CHECK) {
  let bad = 0, total = 0;
  Object.keys(seen).sort().forEach(lesson => {
    const v = RD.check(lesson, seen[lesson]);
    total += seen[lesson].length;
    console.log('  ' + (v.fresh.length ? 'FAIL  ' : 'PASS  ') + lesson + ': ' +
      seen[lesson].length + ' outstanding sentence(s) on screen, ceiling ' + v.ceiling);
    seen[lesson].forEach(t => console.log('          · ' + t.slice(0, 110)));
    v.fresh.forEach(t => { bad++; console.log('          NEW ON SCREEN: ' + t.slice(0, 110)); });
  });
  console.log('\n  ledger exemptions, declared: ' + LD.EXEMPTIONS.join(' · '));
  if (bad) {
    console.log('\nqa-engine-debt: ' + bad + ' engine sentence(s) reached a pupil card that did not render them before.');
    process.exit(1);
  }
  console.log('\nqa-engine-debt: PASS — ' + total + ' outstanding sentence(s) on screen across ' +
    Object.keys(seen).length + ' walk(s), none of them new.');
  process.exit(0);
}

const out = [];
out.push('# ENGINE_STRINGS_RENDERED — which lesson puts which engine sentence in front of a pupil');
out.push('');
out.push('> GENERATED by `ks3-dt/tools/record-tutorial/qa-engine-debt.js` from what the WALKERS');
out.push('> stood on. Do not hand-edit — re-run it after a walk and commit the result.');
out.push('');
out.push('`ENGINE_STRINGS_DEBT.md` says which engine sentences no gate reads. This says which of');
out.push('them a pupil actually MEETS, and it is the ceiling: a lesson may render fewer, never');
out.push('more. A sentence reaching a card that did not render it before fails the walk — which is');
out.push('exactly the shape of "Exit check — part 2", old debt on a new card, on 27 August 2026.');
out.push('');
out.push('Old debt on a signed-off lesson is PRINTED here and on every walk, and never fixed');
out.push('without his word (DFM 221); his approvals are not re-opened (DFM 273a).');
out.push('');
out.push('| lesson | sentence |');
out.push('|---|---|');
Object.keys(seen).sort().forEach(lesson => {
  seen[lesson].slice().sort().forEach(t => {
    out.push('| `' + lesson + '` | ' + String(t).replace(/\|/g, '\\|') + ' |');
  });
});
out.push('');
fs.writeFileSync(RD.BASE, out.join('\n') + '\n');
const n = Object.keys(seen).reduce((a, k) => a + seen[k].length, 0);
console.log('wrote ' + path.relative(path.join(__dirname, '../..'), RD.BASE) +
  ' — ' + n + ' rendered sentence(s) across ' + Object.keys(seen).length + ' walk(s)');
